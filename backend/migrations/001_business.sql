-- 业务状态使用独立 schema；秒级时间保存为双精度，保留亚秒顺序与租约精度。
CREATE TABLE snapshots (
    hash TEXT PRIMARY KEY,
    scenario TEXT NOT NULL,
    version TEXT NOT NULL,
    root TEXT NOT NULL,
    config TEXT NOT NULL,
    resources TEXT NOT NULL,
    created DOUBLE PRECISION NOT NULL
);

CREATE TABLE sessions (
    id TEXT PRIMARY KEY,
    workspace TEXT NOT NULL,
    customer TEXT NOT NULL,
    scenario TEXT NOT NULL,
    snapshot TEXT NOT NULL,
    channel TEXT NOT NULL,
    run_id TEXT NOT NULL,
    state TEXT NOT NULL,
    started DOUBLE PRECISION NOT NULL,
    ended DOUBLE PRECISION,
    reason TEXT,
    purpose TEXT NOT NULL DEFAULT 'session'
);
-- 一个客户同时只能由一个会话执行，场景之间也遵守该约束。
CREATE UNIQUE INDEX one_executor ON sessions(workspace, customer) WHERE state = 'active';
CREATE INDEX sessions_scope_run ON sessions(workspace, scenario, run_id);

CREATE TABLE messages (
    id TEXT PRIMARY KEY,
    workspace TEXT NOT NULL,
    customer TEXT NOT NULL,
    scenario TEXT NOT NULL,
    session TEXT NOT NULL,
    origin TEXT NOT NULL,
    text TEXT NOT NULL,
    final INTEGER NOT NULL,
    audio_item TEXT,
    created DOUBLE PRECISION NOT NULL,
    -- 显式序号用于比较画像证据先后；不依赖数据库隐藏列或任务完成时间。
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX messages_session_order ON messages(session, seq);

CREATE TABLE audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace TEXT NOT NULL,
    customer TEXT NOT NULL,
    scenario TEXT NOT NULL,
    session TEXT NOT NULL,
    kind TEXT NOT NULL,
    payload TEXT NOT NULL,
    created DOUBLE PRECISION NOT NULL
);
CREATE INDEX audit_session_order ON audit(session, id);

CREATE TABLE memory (
    id TEXT PRIMARY KEY,
    workspace TEXT NOT NULL,
    customer TEXT NOT NULL,
    scenario TEXT NOT NULL,
    field TEXT NOT NULL,
    semantic_version TEXT NOT NULL,
    version INTEGER NOT NULL,
    value TEXT NOT NULL,
    status TEXT NOT NULL,
    source_kind TEXT NOT NULL,
    message_id TEXT NOT NULL,
    session TEXT NOT NULL,
    quote TEXT NOT NULL,
    quote_start INTEGER NOT NULL,
    recorded DOUBLE PRECISION NOT NULL,
    expires DOUBLE PRECISION NOT NULL,
    supersedes TEXT,
    operation_id TEXT NOT NULL,
    request_hash TEXT NOT NULL,
    UNIQUE(workspace, customer, scenario, field, version),
    UNIQUE(workspace, customer, scenario, operation_id)
);
CREATE INDEX memory_message ON memory(message_id);

CREATE TABLE profile_jobs (
    session_id TEXT PRIMARY KEY,
    status TEXT NOT NULL,
    baseline_json TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt DOUBLE PRECISION NOT NULL DEFAULT 0,
    lease_until DOUBLE PRECISION NOT NULL DEFAULT 0,
    error TEXT,
    result_json TEXT
);
CREATE INDEX profile_jobs_ready ON profile_jobs(status, next_attempt);

CREATE TABLE runtime_sessions (
    session_id TEXT PRIMARY KEY,
    scenario_id TEXT NOT NULL,
    snapshot_hash TEXT NOT NULL,
    channel TEXT NOT NULL,
    status TEXT NOT NULL,
    started_at DOUBLE PRECISION NOT NULL,
    opening_sent INTEGER NOT NULL DEFAULT 0,
    state_json TEXT,
    metadata_json TEXT NOT NULL DEFAULT '{}'
);

CREATE TABLE runtime_events (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL,
    type TEXT NOT NULL,
    at DOUBLE PRECISION NOT NULL,
    data_json TEXT NOT NULL
);
CREATE INDEX runtime_events_session ON runtime_events(session_id, seq);
